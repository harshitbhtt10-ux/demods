fun getAppStrings(code: String): Strings {
    return when (code) {
        "hi", "hin", "bho" -> HindiStrings
        "pa" -> PunjabiStrings
        "bn", "as" -> BengaliStrings
        "gu" -> GujaratiStrings
        "mr" -> MarathiStrings
        "ta" -> TamilStrings
        "te" -> TeluguStrings
        else -> EnglishStrings
    }
}
